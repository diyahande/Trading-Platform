#!/usr/bin/env node
// Writes src/app/core/config/app-env.generated.ts from the repo-root .env.
// Angular cannot read .env at runtime, so the values are baked in at build time.
// Real environment variables take precedence over the file, as in the other loaders.
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const frontendRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const rootEnvPath = resolve(frontendRoot, '..', '.env');
const outPath = join(frontendRoot, 'src', 'app', 'core', 'config', 'app-env.generated.ts');

const REQUIRED = ['AUTH_SERVICE_URL', 'TRADE_API_URL', 'AI_CHAT_URL', 'FRANKFURTER_RATES_URL', 'CORS_ALLOWED_ORIGINS'];

function readDotEnv(path) {
  if (!existsSync(path)) return {};
  const values = {};
  for (const line of readFileSync(path, 'utf8').split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (!match || match[0].trim().startsWith('#')) continue;
    values[match[1]] = match[2].replace(/^(['"])(.*)\1$/, '$2');
  }
  return values;
}

const fileValues = readDotEnv(rootEnvPath);
const value = (name) => process.env[name] || fileValues[name] || '';

const missing = REQUIRED.filter((name) => !value(name));
if (missing.length) {
  console.error(`[generate-env] Missing ${missing.join(', ')}. Set them in the repo-root .env (see .env.example).`);
  process.exit(1);
}

const config = {
  authApiUrl: value('AUTH_SERVICE_URL'),
  tradeApiUrl: value('TRADE_API_URL'),
  aiChatUrl: value('AI_CHAT_URL'),
  ratesUrl: value('FRANKFURTER_RATES_URL'),
  allowedOrigins: value('CORS_ALLOWED_ORIGINS')
    .split(',')
    .map((origin) => origin.trim())
    .filter(Boolean),
};

const source = `// Generated by frontend/scripts/generate-env.mjs from the repo-root .env. Do not edit.
export const APP_ENV = ${JSON.stringify(config, null, 2)} as const;
`;

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, source);
console.log(`[generate-env] Wrote ${outPath.replaceAll('\\', '/')}`);
